// ============================================================
// 练习 e02: 文本节点 — 参考答案
//
// 核心知识点:
//   - 字符串文本 "..." 语法
//   - 多行文本并列拼接
// ============================================================

use leptos::prelude::*;

#[component]
fn Exercise() -> impl IntoView {
    view! {
        // 第 1 段 — 单行字符串文本
        <p>"这是单行字符串文本"</p>

        // 第 2 段 — 多行文本拼接（多个 "文本" 并列写会自动拼接）
        <p>"这是第一行文本" "这是第二行文本，紧接在后面"</p>

        // 第 3 段 — 含空格的文本拼接（在 "文本" 前后加空格控制间距）
        <p>"Hello, " "Leptos!"</p>
    }
}

fn main() {
    mount_to_body(Exercise);
}
