// ============================================================
// 练习 e08: 注释写法 — 参考答案
//
// 核心知识点:
//   - /* */ 块注释（可跨行）
//   - // 行注释（Leptos 0.9 nightly 支持）
//   - 注释在编译时被忽略，不影响渲染结果
// ============================================================

use leptos::prelude::*;

#[component]
fn Exercise() -> impl IntoView {
    view! {
        <div>
            /* 这是 view! 宏内的块注释 */
            <p>"注释不会出现在渲染结果中"</p>

            /* 多行注释
               也可以跨行书写
            */
            <p>"上面的注释在编译时会被忽略"</p>

            // 行注释也支持（Leptos 0.9 nightly）
            <p>"行注释同样不会渲染"</p>
        </div>
    }
}

fn main() {
    mount_to_body(Exercise);
}
