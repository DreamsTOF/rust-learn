use leptos::prelude::*;

#[component]
fn Exercise() -> impl IntoView {
    // TODO: 在 view! 中返回含文本的页面
    view! {
        // TODO: 第 1 段 — 单行字符串文本
        // 提示: 用 "文本" 包裹字符串
        <p>"这是单行字符串文本"</p>

        // TODO: 第 2 段 — 多行文本拼接
        // 提示: 多个 "文本" 并列写会自动拼接
        <p>"这是第一行文本" "这是第二行文本，紧接在后面"</p>

        // TODO: 第 3 段 — 含空格的文本拼接
        // 提示: 在 "文本" 前后加空格控制间距
        <p>"Hello, " "Leptos!"</p>
    }
}

fn main() {
    mount_to_body(Exercise);
}

